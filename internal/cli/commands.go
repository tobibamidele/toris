// ─── toris health ─────────────────────────────────────────────────────────────

func newHealthCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "health",
		Short: "Run health checks against all cluster nodes",
		Long: `Performs the full 5-level health check (transport, ready, live, role, policy)
against every node in the cluster and reports the results.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, log, err := loadConfig()
			if err != nil {
				return err
			}

			ctx, cancel := context.WithTimeout(context.Background(), cfg.Timeouts.Connect*3)
			defer cancel()

			tools, err := pgback.CheckTools(ctx)
			if err != nil {
				return fmt.Errorf("tool check failed: %w", err)
			}

			backend := pgback.New(log)
			defer backend.CloseAll()

			var snapshots []*model.HealthSnapshot
			for _, nc := range cfg.Cluster.Nodes {
				node := &model.Node{
					ID:   nc.ID,
					Host: nc.Host,
					Port: nc.Port,
				}
				snap, err := backend.Health(ctx, node)
				if err != nil {
					log.Warn("health check error", "node", nc.ID, "error", err.Error())
					snap = &model.HealthSnapshot{
						NodeID:    nc.ID,
						Level:     model.HealthLevelUnreachable,
						CheckedAt: time.Now().UTC(),
						Errors:    []string{err.Error()},
					}
				}

				// Also run pg_isready for the Level 2 signal.
				nc2 := nc // capture
				isReadyNode := &model.Node{ID: nc2.ID, Host: nc2.Host, Port: nc2.Port}
				if res, err := pgback.PgIsReady(ctx, tools, isReadyNode, 5*time.Second); err == nil {
					snap.ReadyOK = res.Ready
				}

				snapshots = append(snapshots, snap)
			}

			if cfg.OutputFormat == "json" {
				printJSON(snapshots)
			} else {
				printHealthTable(snapshots)
			}
			return nil
		},
	}
}

func printHealthTable(snaps []*model.HealthSnapshot) {
	fmt.Printf("%-16s %-10s %-10s  TCP  RDY  SQL  ROLE POL  %s\n",
		"NODE", "ROLE", "LEVEL", "ERRORS")
	fmt.Println("─────────────────────────────────────────────────────────────────────")
	for _, s := range snaps {
		tcp := boolMark(s.TransportOK)
		rdy := boolMark(s.ReadyOK)
		sql := boolMark(s.LiveOK)
		role := boolMark(s.RoleOK)
		pol := boolMark(s.PolicyOK)
		errStr := ""
		if len(s.Errors) > 0 {
			errStr = s.Errors[0]
		}
		fmt.Printf("%-16s %-10s L%-9d %s    %s    %s    %s    %s    %s\n",
			s.NodeID, s.Role, s.Level, tcp, rdy, sql, role, pol, errStr)
	}
}

func boolMark(b bool) string {
	if b {
		return "✓"
	}
	return "✗"
}

// ─── toris backup ─────────────────────────────────────────────────────────────

func newBackupCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "backup",
		Short: "Backup management commands",
	}

	// backup create
	createCmd := &cobra.Command{
		Use:   "create",
		Short: "Create a new backup of the primary node",
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, log, err := loadConfig()
			if err != nil {
				return err
			}
			ctx, cancel := context.WithTimeout(context.Background(), cfg.Timeouts.Backup)
			defer cancel()

			tools, err := pgback.CheckTools(ctx)
			if err != nil {
				return err
			}
			if len(cfg.Cluster.Nodes) == 0 {
				return fmt.Errorf("no nodes configured")
			}
			nc := cfg.Cluster.Nodes[0]
			node := &model.Node{ID: nc.ID, Host: nc.Host, Port: nc.Port}
			replicationUser, replicationPass := resolveAuth(cfg, nc.AuthProfile)

			store, storeErr := fsstorage.New(cfg.Backup.BaseDir)
			if storeErr != nil {
				return fmt.Errorf("initialising storage: %w", storeErr)
			}

			// Wire the backup store if control DB is reachable; nil otherwise (non-fatal).
			var bs *backup.Store
			if pool, poolErr := connectControlDB(ctx, cfg.ControlDSN); poolErr == nil {
				defer pool.Close()
				bs = backup.NewStore(pool)
			} else {
				log.Warn("control DB unavailable — backup record will not be persisted",
					"error", poolErr.Error())
			}

			pl := backup.NewPipeline(log, nil, tools, store, nil, bs)
			b, err := pl.Create(ctx, backup.CreateOptions{
				Node:                node,
				ClusterID:           cfg.Cluster.ID,
				StagingDir:          cfg.Backup.BaseDir,
				DryRun:              gFlags.dryRun,
				OffSiteRequired:     cfg.Backup.OffSiteRequired,
				BackupTimeout:       cfg.Timeouts.Backup,
				VerifyTimeout:       cfg.Timeouts.ToolExec,
				ReplicationUser:     replicationUser,
				ReplicationPassword: replicationPass,
			})
			if err != nil {
				if b != nil {
					log.Error("backup failed", "backup_id", b.ID, "error", err.Error())
				}
				return err
			}
			if cfg.OutputFormat == "json" || gFlags.outputFormat == "json" {
				printJSON(b)
			} else {
				fmt.Printf("Backup %s\n", b.ID)
				fmt.Printf("  Status  : %s\n", b.Status)
				fmt.Printf("  Path    : %s\n", b.StoragePath)
				fmt.Printf("  Size    : %s\n", formatBytes(b.SizeBytes))
				fmt.Printf("  Started : %s\n", b.StartedAt.Format(time.RFC3339))
			}
			return nil
		},
	}

	// backup verify
	verifyCmd := &cobra.Command{
		Use:   "verify <backup-id|path>",
		Short: "Verify an existing backup's integrity",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, log, err := loadConfig()
			if err != nil {
				return err
			}
			ctx, cancel := context.WithTimeout(context.Background(), cfg.Timeouts.ToolExec)
			defer cancel()

			tools, err := pgback.CheckTools(ctx)
			if err != nil {
				return err
			}
			backupPath := args[0]
			res, err := pgback.PgVerifyBackup(ctx, log, tools, backupPath, cfg.Timeouts.ToolExec)
			if err != nil {
				return fmt.Errorf("verification failed: %w", err)
			}
			if cfg.OutputFormat == "json" || gFlags.outputFormat == "json" {
				printJSON(map[string]any{
					"status":   "verified",
					"path":     backupPath,
					"duration": res.Duration.String(),
				})
			} else {
				fmt.Printf("Backup verified: %s (%s)\n", backupPath, util.FormatDuration(res.Duration))
			}
			return nil
		},
	}

	// backup list
	listCmd := &cobra.Command{
		Use:   "list",
		Short: "List all backups",
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, _, err := loadConfig()
			if err != nil {
				return err
			}
			ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
			defer cancel()
			pool, poolErr := connectControlDB(ctx, cfg.ControlDSN)
			if poolErr != nil {
				return fmt.Errorf("connecting to control DB: %w", poolErr)
			}
			defer pool.Close()
			bs := backup.NewStore(pool)
			records, listErr := bs.List(ctx, cfg.Cluster.ID, 0)
			if listErr != nil {
				return fmt.Errorf("listing backups: %w", listErr)
			}
			if cfg.OutputFormat == "json" || gFlags.outputFormat == "json" {
				printJSON(records)
			} else {
				if len(records) == 0 {
					fmt.Println("No backups found.")
					return nil
				}
				fmt.Printf("%-32s  %-10s  %-10s  %s\n", "ID", "STATUS", "SIZE", "STARTED")
				fmt.Println("─────────────────────────────────────────────────────────────────")
				for _, b := range records {
					fmt.Printf("%-32s  %-10s  %-10s  %s\n",
						b.ID, string(b.Status),
						formatBytes(b.SizeBytes),
						b.StartedAt.Format(time.RFC3339))
				}
			}
			return nil
		},
	}

	// backup prune
	pruneCmd := &cobra.Command{
		Use:   "prune",
		Short: "Apply retention policy and remove old backups",
		Long: `Evaluates the configured retention policy and removes artifacts from storage
for backups that exceed the policy thresholds. The backup record in the control
DB is marked pruned but not deleted (kept for audit history).`,
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, log, err := loadConfig()
			if err != nil {
				return err
			}
			if !gFlags.force {
				ok, _ := confirmDestructive("apply retention policy and delete old backup artifacts?")
				if !ok {
					fmt.Println("aborted")
					return nil
				}
			}
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
			defer cancel()
			pool, poolErr := connectControlDB(ctx, cfg.ControlDSN)
			if poolErr != nil {
				return fmt.Errorf("connecting to control DB: %w", poolErr)
			}
			defer pool.Close()
			bs := backup.NewStore(pool)
			records, listErr := bs.List(ctx, cfg.Cluster.ID, 0)
			if listErr != nil {
				return fmt.Errorf("listing backups: %w", listErr)
			}
			store, storeErr := fsstorage.New(cfg.Backup.BaseDir)
			if storeErr != nil {
				return fmt.Errorf("opening storage: %w", storeErr)
			}
			policy := model.RetentionPolicy{
				MinCount:   cfg.Backup.Retention.MinCount,
				MaxAgeDays: cfg.Backup.Retention.MaxAgeDays,
				KeepFailed: cfg.Backup.Retention.KeepFailed,
			}
			enf := retention.New(log, store, policy)
			pl := backup.NewPipeline(log, nil, nil, store, enf, bs)
			pruned, pruneErr := pl.Prune(ctx, records)
			if pruneErr != nil {
				return fmt.Errorf("prune failed: %w", pruneErr)
			}
			if cfg.OutputFormat == "json" || gFlags.outputFormat == "json" {
				printJSON(map[string]any{"pruned": pruned, "count": len(pruned)})
			} else {
				if len(pruned) == 0 {
					fmt.Println("No backups pruned (retention policy satisfied).")
				} else {
					fmt.Printf("Pruned %d backup(s):\n", len(pruned))
					for _, id := range pruned {
						fmt.Printf("  %s\n", id)
					}
				}
			}
			return nil
		},
	}

	cmd.AddCommand(createCmd, verifyCmd, listCmd, pruneCmd)
	return cmd
}

// ─── toris restore ────────────────────────────────────────────────────────────

func newRestoreCmd() *cobra.Command {
	var backupID, targetDir string
	cmd := &cobra.Command{
		Use:   "restore",
		Short: "Restore a backup to a node",
		Long: `Restores a verified backup into a target data directory.
The target directory must be empty. PostgreSQL must not be running on it.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			if backupID == "" {
				return fmt.Errorf("--backup-id is required")
			}
			if targetDir == "" {
				return fmt.Errorf("--target-dir is required")
			}
			cfg, log, err := loadConfig()
			if err != nil {
				return err
			}
			if !gFlags.force {
				ok, _ := confirmDestructive(
					fmt.Sprintf("restore backup %s into %s?", backupID, targetDir))
				if !ok {
					fmt.Println("aborted")
					return nil
				}
			}
			store, storeErr := fsstorage.New(cfg.Backup.BaseDir)
			if storeErr != nil {
				return fmt.Errorf("opening storage: %w", storeErr)
			}
			engine := restoreEngine(log, store)
			ctx, cancel := context.WithTimeout(context.Background(), cfg.Timeouts.Restore)
			defer cancel()
			job, jobErr := engine.Run(ctx, restoreOptions(backupID, targetDir, cfg))
			if jobErr != nil {
				if job != nil {
					log.Error("restore failed", "job_id", job.ID, "artifact_dir", job.ArtifactDir)
				}
				return jobErr
			}
			if cfg.OutputFormat == "json" || gFlags.outputFormat == "json" {
				printJSON(job)
			} else {
				fmt.Printf("Restore complete\n")
				fmt.Printf("  Job     : %s\n", job.ID)
				fmt.Printf("  Status  : %s\n", string(job.Status))
				if job.FinishedAt != nil {
					fmt.Printf("  Duration: %s\n", util.FormatDuration(job.FinishedAt.Sub(job.StartedAt)))
				}
			}
			return nil
		},
	}
	cmd.Flags().StringVar(&backupID, "backup-id", "", "ID of the backup to restore (required)")
	cmd.Flags().StringVar(&targetDir, "target-dir", "", "target PostgreSQL data directory (required)")
	return cmd
}

