// resolveAuth finds the username and password for a named auth profile.
func resolveAuth(cfg *config.Config, profileName string) (string, string) {
	for _, p := range cfg.Auth.Profiles {
		if p.Name == profileName {
			return p.Username, p.Password
		}
	}
	return "", ""
}

// formatBytes formats byte counts as human-readable strings.
func formatBytes(b int64) string {
	const unit = 1024
	if b < unit {
		return fmt.Sprintf("%d B", b)
	}
	div, exp := int64(unit), 0
	for n := b / unit; n >= unit; n /= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %ciB", float64(b)/float64(div), "KMGTPE"[exp])
}

