func newInitCmd() *cobra.Command {
	var outPath string
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Create a starter configuration file",
		Long: `Writes a commented toris.yaml to the specified path.
Edit it to match your cluster, then run 'toris config validate' to verify.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			if outPath == "" {
				outPath = "toris.yaml"
			}
			if _, err := os.Stat(outPath); err == nil && !gFlags.force {
				return fmt.Errorf("%s already exists; use --force to overwrite", outPath)
			}
			return writeStarterConfig(outPath)
		},
	}
	cmd.Flags().StringVarP(&outPath, "out", "o", "toris.yaml", "path to write config file")
	return cmd
}

